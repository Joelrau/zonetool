			bool map_stream_routing_iw3_to_h1(unsigned char iw3_source, unsigned char iw3_dest,
				unsigned char& h1_source, unsigned char& h1_dest, unsigned char& h1_mask)
			{
				// --- source ---
				// IW3/IW5 sources 0..4 (POSITION/COLOR/TEXCOORD_0/NORMAL/TANGENT) share H1 values 0..4.
				// IW3 "optional" sources 5..8 have no named H1 counterpart in the struct; H1 defines 23
				// sources total, so we pass the value through verbatim and flag it UNVERIFIED.
				if (iw3_source <= IW3_STREAM_SRC_TANGENT)
				{
					h1_source = iw3_source; // exact: same enum value on both sides
				}
				else if (iw3_source < IW3_STREAM_SRC_COUNT)
				{
					h1_source = iw3_source; // UNVERIFIED: IW3 optional source pass-through (5..8)
				}
				else
				{
					return false;
				}
				if (h1_source >= H1_STREAM_SRC_COUNT)
				{
					return false;
				}

				// --- dest ---
				// IW3/IW5 dests 0..1 (POSITION/NORMAL) share H1 values 0..1. IW3 dests 2..12 have no
				// named H1 counterpart; H1 defines 33 dests total, so pass through and flag UNVERIFIED.
				if (iw3_dest <= IW3_STREAM_DST_NORMAL)
				{
					h1_dest = iw3_dest; // exact: same enum value on both sides
				}
				else if (iw3_dest < IW3_STREAM_DST_COUNT)
				{
					h1_dest = iw3_dest; // UNVERIFIED: IW3 dest pass-through (2..12)
				}
				else
				{
					return false;
				}
				if (h1_dest >= H1_STREAM_DST_COUNT)
				{
					return false;
				}

				// --- mask ---
				// IW3 MaterialStreamRouting has no mask byte; H1 requires one (component write mask).
				// UNVERIFIED heuristic: derive a plausible component mask from the source semantic.
				// The caller should refine this against the real target vertex format when known.
				switch (iw3_source)
				{
				case IW3_STREAM_SRC_COLOR:
					h1_mask = 0x0F; // rgba
					break;
				case IW3_STREAM_SRC_TEXCOORD_0:
				case IW3_STREAM_SRC_TEXCOORD_1:
				case IW3_STREAM_SRC_TEXCOORD_2:
					h1_mask = 0x03; // uv
					break;
				case IW3_STREAM_SRC_POSITION:
				case IW3_STREAM_SRC_NORMAL:
				case IW3_STREAM_SRC_TANGENT:
					h1_mask = 0x07; // xyz
					break;
				default:
					h1_mask = 0x0F; // UNVERIFIED: write-all fallback
					break;
				}
				return true;
			}

			int map_arg_type_iw3_to_h1(int iw3_type, bool& is_pixel_stage)
			{
				// Default to vertex stage; overridden per-case for the pixel variants.
				is_pixel_stage = false;
				switch (iw3_type)
				{
				case IW3_MTL_ARG_MATERIAL_VERTEX_CONST:
					is_pixel_stage = false;
					return H1_MTL_ARG_MATERIAL_CONST;
				case IW3_MTL_ARG_LITERAL_VERTEX_CONST:
					is_pixel_stage = false;
					return H1_MTL_ARG_LITERAL_CONST;
				case IW3_MTL_ARG_CODE_VERTEX_CONST:
					is_pixel_stage = false;
					return H1_MTL_ARG_CODE_CONST;
				case IW3_MTL_ARG_CODE_PIXEL_CONST:
					is_pixel_stage = true;
					return H1_MTL_ARG_CODE_CONST;
				case IW3_MTL_ARG_MATERIAL_PIXEL_CONST:
					is_pixel_stage = true;
					return H1_MTL_ARG_MATERIAL_CONST;
				case IW3_MTL_ARG_LITERAL_PIXEL_CONST:
					is_pixel_stage = true;
					return H1_MTL_ARG_LITERAL_CONST;
				case IW3_MTL_ARG_MATERIAL_PIXEL_SAMPLER:
					// DX9 combined sampler -> H1 material *texture*; caller adds companion MATERIAL_SAMPLER.
					is_pixel_stage = true;
					return H1_MTL_ARG_MATERIAL_TEXTURE;
				case IW3_MTL_ARG_CODE_PIXEL_SAMPLER:
					// DX9 combined code sampler -> H1 code *texture*; caller adds companion CODE_SAMPLER.
					is_pixel_stage = true;
					return H1_MTL_ARG_CODE_TEXTURE;
				default:
					return -1;
				}
			}

